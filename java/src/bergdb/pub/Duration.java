package bergdb.pub;

import java.util.Locale;

import bergdb.pub.util.Clock;

/**
 * An instance of this class represents a duration of time (immutable, non-negative).
 * The resolution is 100 nanoseconds and the duration is stored as a long internally.
 * 
 * @author Frans Lundberg
 */
public class Duration {
    
    /**
     * Longest possible duration. Equals Long.MAX_VALUE * 100 nanoseconds = 29 000 years.
     */
    public static final Duration MAX = new Duration(Long.MAX_VALUE);
    
    private static final double UNITS_PER_SECOND = (double) Clock.UNITS_PER_SEC;
    private static final double UNITS_PER_MINUTE = UNITS_PER_SECOND * 60.0;
    private static final double UNITS_PER_HOUR = UNITS_PER_MINUTE * 60.0;
    private static final double UNITS_PER_DAY = UNITS_PER_HOUR * 24.0;

    private final long units;
    
    private Duration(long units) {
        if (units < 0) {
            throw new IllegalArgumentException("Duration must be non-negative, " + units + ".");
        }
        this.units = units;
    }
    
    /**
     * Returns the duration measured in clock units (see Clock).
     */
    public long units() {
        return units;
    }
    
    /**
     * Creates a Duration specified in seconds, rounded to the nearest clock unit (100 ns).
     * A value above MAX's, about 922 billion seconds, positive infinity included, gives MAX.
     *
     * @throws IllegalArgumentException  If seconds is NaN (bergdb 020-21, Q1), or the
     *     duration, rounded to clock units, is negative.
     */
    public static Duration seconds(double seconds) {
        if (Double.isNaN(seconds)) {
            // Frans, 2026-11-09 (bergdb 020-21, Q1): Math.round(NaN) is 0, so NaN gave a
            // duration of 0; a NaN means no duration, as a negative value does.
            throw new IllegalArgumentException("seconds is NaN, not a duration");
        }
        return new Duration(Math.round(seconds * UNITS_PER_SECOND));
    }

    /**
     * Creates a Duration specified in clock units.
     * 
     * @see Clock
     * @param units  Clock units.
     * @throws IllegalArgumentException  If units is negative (bergdb 020-25).
     */
    public static Duration units(long units) {
        return new Duration(units);
    }
    
    @Override
    public int hashCode() {
        // Generated by Eclipse.
        final int prime = 31;
        int result = 1;
        result = prime * result + (int) (units ^ (units >>> 32));
        return result;
    }

    @Override
    public boolean equals(Object obj) {
        // Generated by Eclipse.
        
        if (this == obj) {
            return true;
        }
        if (obj == null) {
            return false;
        }
        if (getClass() != obj.getClass()) {
            return false;
        }
        Duration other = (Duration) obj;
        if (units != other.units) {
            return false;
        }
        return true;
    }

    public String toString() {
        if (units < 120.0 * UNITS_PER_SECOND) {
            return toStringSeconds();
        } else if (units < 120.0 * UNITS_PER_MINUTE) {
            return toStringMinutes();
        } else if (units < 48.0 * UNITS_PER_HOUR) {
            return toStringHours();
        } else {
            return toStringDays();
        }
    }
    
    private String toStringSeconds() {
        double s = units / UNITS_PER_SECOND;
        String result;
        
        if (s < 0.01) {
            result = String.format(Locale.US, "%f s", s);
        } else if (s < 2.0) {
            result = String.format(Locale.US, "%.3f s", s);
        } else {
            result = String.format(Locale.US, "%.1f s", s);
        }
        return result;
    }
    
    private String toStringMinutes() {
        double s = units / UNITS_PER_MINUTE;
        return String.format(Locale.US, "%.2f min", s);
    }
    
    private String toStringHours() {
        double h = units / UNITS_PER_HOUR;
        return String.format(Locale.US, "%.2f h", h);
    }
    
    private String toStringDays() {
        double days = units / UNITS_PER_DAY;
        return String.format(Locale.US, "%.2f days", days);
    }
}
