#!/usr/bin/env python3
"""025-02 tool (2026-11-14): writes the name map, names.md, for the names that items cite.
Changed by step 3 (names), 2026-11-14: a renamed name that items cite for an earlier statement
is listed and marked in section 1, and marked in sections 2 and 3 where the earlier statement is listed (original:
cleanup/names/names.py.orig).

Usage: python3 names.py REPO PRUNE_REPORT SUPERSEDED [RENAMES] > names.md
  REPO          a checkout of the repo whose items/ give the citations (the base, eb1a04a0 or
                later: the provers' clone before its own item edits is fine)
  PRUNE_REPORT  prune.py's report as applied (DEAD lines)
  SUPERSEDED    superseded.txt (old successor | old - reason)
  RENAMES       the names step's table (old new; FILE lines are listed too), optional
A name is in the map when an item cites it in backquotes (its last component or its
dotted tail) and it was removed or renamed. Items are named by their IDs (024-12 and so on).
"""
import os, re, sys, collections

repo, report, sup = sys.argv[1:4]
renames_f = sys.argv[4] if len(sys.argv) > 4 else None

cites = collections.defaultdict(set)
for dp, _, fs in os.walk(os.path.join(repo, "items")):
    for f in fs:
        if not f.endswith(".md"):
            continue
        p = os.path.join(dp, f)
        if "02-proof-cleanup" in p:
            continue  # the cleanup's own files (this plan, names.md) are not citations
        rel = os.path.relpath(p, os.path.join(repo, "items")).split(os.sep)
        iid = rel[0][:3] + ("-" + rel[1][:2] if len(rel) > 1 and rel[1][:2].isdigit() else "")
        for m in re.findall(r"`([A-Za-z_][A-Za-z0-9_.']*)`", open(p, errors="replace").read()):
            cites[m].add(iid)

def short(n):
    return n[len("SIS.Tree."):] if n.startswith("SIS.Tree.") else n

def cited(n):
    s = short(n)
    ids = set(cites.get(s, set())) | set(cites.get(s.split(".")[-1], set()))
    return ", ".join(sorted(ids))

ren, ren_files = {}, []
if renames_f:
    for l in open(renames_f):
        l = l.split("#", 1)[0].strip()
        if not l:
            continue
        p = l.split()
        if p[0] == "FILE":
            ren_files.append((p[1], p[2]))
        else:
            ren[short(p[0])] = short(p[1])

succ = {}
for l in open(sup):
    l = l.strip()
    if l and not l.startswith("#"):
        a, b = l.split(None, 1)
        succ[a] = b

dead = [short(l.split()[3]) for l in open(report) if l.startswith("DEAD")]
out = ["# 025-02, the name map", "",
       "Old name → new name for every declaration of lean/SIS/Tree that an item cites and that",
       "the cleanup of 2026-11-14 renamed or removed. Generated by names.py from the prune's report,",
       "superseded.txt and the names step's table; the items that cite each name are in brackets.",
       "Names not listed are unchanged. The premises' names (d4, l4, hchk, htb, hMSF, hCoF, hU, hHL,",
       "hCoU, hMF) and the definitions in their statements are unchanged. A new name that items",
       "cite for an earlier, removed statement is marked, here and where sections 2 and 3 list the",
       "earlier statement.", ""]
dead_set = {short(l.split()[3]) for l in open(report) if l.startswith("DEAD")}
out += ["# 1. Renamed", ""]
for a, b in sorted(ren.items()):
    c, cb = cited(a), cited(b)
    if c or cb:
        reuse = f" (the name of an earlier, removed statement, cited in {cb})" if cb else ""
        out.append(f"- `{a}` → `{b}`{reuse}" + (f" [{c}]" if c else ""))
for a, b in ren_files:
    out.append(f"- file {a} → {b}")
# a removed name that step 3 gave to a later statement: an item that cites it means the earlier one
reused = {b: a for a, b in ren.items() if cited(b)}
def now(a):
    return f"; the name is now the renamed `{reused[a]}`'s" if a in reused else ""
out += ["", "# 2. Removed as an earlier version", ""]
for a in sorted(set(dead)):
    if a in succ and cited(a):
        b = succ[a]
        if b.startswith("-"):
            out.append(f"- `{a}`: removed, {b[1:].strip()}{now(a)} [{cited(a)}]")
        else:
            out.append(f"- `{a}`: removed; superseded by `{ren.get(b, b)}`{now(a)} [{cited(a)}]")
out += ["", "# 3. Removed, used by no root", "",
        "Not used by the top theorem, the model, the checkers or any file outside lean/SIS/Tree,",
        "and not a building block that the open premises' plans name (keep.txt).", ""]
for a in sorted(set(dead)):
    if a not in succ and cited(a):
        out.append(f"- `{a}`{now(a).replace('; ', ': ', 1)} [{cited(a)}]")
print("\n".join(out))
